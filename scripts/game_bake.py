"""Bakes the written missions and the street crowd into the mockup.

    python scripts/game_bake.py                       # content repo beside this one
    python scripts/game_bake.py --content ../fluidez-es-ni

The missions live in `scenicprints/fluidez-es-ni` because they are content and
they ship in the pack the app downloads. The mockup lives here and has to stay
ONE file you can open in a browser with no build and no server, so it cannot
fetch them: they get baked in.

WHERE PEOPLE STAND. The missions do not carry coordinates and should not --
they are written against a district, not against a tile, and a tile number
would rot the moment the map is rebuilt at a different scale. So placement
lives here, as a real named place plus an offset in tiles, and the named
places come out of the OSM extract. Anything without an entry is dropped near
its district anchor AND REPORTED, because a mission that quietly piles up on
top of another one is a mission nobody will find.
"""
