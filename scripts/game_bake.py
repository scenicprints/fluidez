# How far a district's people spread out from its anchor, as a multiplier on
# the offsets below.
#
# Kevin: "Spread out the people so the quests arent so concentrated." He was
# right: nine of the twelve districts hung every mission off a single named
# place with offsets inside about seventy metres, which is one screenful. You
# walked into a knot of people and then had several hundred metres of nothing.
# These widen a district to roughly two or three hundred metres -- a few blocks
# you walk THROUGH rather than a dot you stand on.
#
# They are not all the same because the ground is not. Malecon runs along the
# water and Afuera along one road out of town, so pushing those out hard just
# presses people against the shore or the verge; El Centro, Las fiestas and
# Pantanal were already spread over real separate landmarks and need less.
SPREAD = {
    'centro': 1.7, 'mercado': 2.6, 'xalteva': 1.8, 'guadalupe': 2.8,
    'terminal': 2.4, 'trabajo': 2.8, 'tramites': 2.6, 'fiestas': 1.8,
    'barrio': 2.6, 'pantanal': 1.6, 'malecon': 1.7, 'afuera': 1.8,
}


def spread_of(mid):
    return SPREAD.get(str(mid).split('-')[0], 2.0)


def widen(mid, dx, dy):
    """Push an offset out from its anchor by its district's spread.

    Scaling rather than re-authoring keeps every arrangement the offsets
    already describe -- the hostel stays a block west and south of the plaza,
    it is just further west and further south. Placement is snapped to a
    walkable, reachable, unoccupied tile at runtime, so a widened offset that
    lands in a block ends up in the nearest street rather than in a wall.
    """
    f = spread_of(mid)
    return int(round(dx * f)), int(round(dy * f))

